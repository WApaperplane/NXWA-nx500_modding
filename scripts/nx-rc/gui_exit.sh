#!/bin/bash
#=====================================================================
# gui_exit.sh —— 退出 FilmLab 图形选择器（触屏"取消"/返回 键调用）
#=====================================================================
# 社区 mod 框架的退出约定（从 EV_EV.sh 学到）：
#   killall -q mod_gui 关闭菜单本体
#   killall -q <自定义进程> 关闭我们自己的 X11 窗口
#
# 相机上的用法：
#   · 触屏点「取消」→ mod_gui 调用本脚本
#   · 机身 EV_OK 键 → EV_OK.sh
#   · telnet: sh /opt/usr/nx-ks/gui_exit.sh
#=====================================================================

# 关掉 X11 配方选择器（进程名是二进制名，不是 .arm）
killall -q nxflab.arm 2>/dev/null

# 给个反馈让用户知道关了
echo "FilmLab 已退出" > /mnt/mmc/filmlab/last.log 2>/dev/null
