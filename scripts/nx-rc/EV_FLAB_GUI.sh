#!/bin/sh
#=====================================================================
# EV_FLAB_GUI.sh —— 打开 mod_gui 之前先同步 FilmLab 菜单
#=====================================================================
# ★ 为什么需要这个：
#   mod_gui 菜单页是静态文本文件。如果手写，往 SD 卡加配方但不改菜单，
#   界面上就看不到新配方 —— "配方数不限"就是空话。
#   本脚本在 mod_gui 启动前跑 filmlab.sh mkgui，从 SD 卡 recipes.json
#   重新生成 gui_filmlab1b.NX500，实现菜单与配方库永远同步。
#
# 用法：把下面这行加进 EV_EV.sh（mod_gui 的官方入口）末尾，或替换它：
#     /opt/usr/nx-ks/EV_FLAB_GUI.sh
#=====================================================================

F=/opt/usr/nx-ks/filmlab.sh
[ -x "$F" ] || exit 0

# mkgui 失败（配方库为空/SD 卡未插）不应挡住用户进菜单 → 静默放行
"$F" mkgui >/dev/null 2>&1

exit 0
