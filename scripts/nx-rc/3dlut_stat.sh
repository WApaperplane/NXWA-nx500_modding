#!/bin/sh
#=====================================================================
# 3dlut_stat.sh — 回读 3D LUT 寄存器状态
#---------------------------------------------------------------------
# ★ 这是判断"改了生效没有"的第一手硬件证据。
#   判据：+0x008 执行后【保持为 1】= 硬件接受了启动
#         （之前每次实验都被硬件清零 ⇒ 硬件拒绝了启动）
#
# 只读，无副作用。
#=====================================================================

BB=/opt/usr/nx-ks/busybox
EPBASE=0x2082b000

RD=/opt/usr/nx-ks/epreg.arm
[ -x "$RD" ] || { echo "ERR: 缺 epreg.arm"; exit 1; }

[ -c /dev/drime5_ep ] || { echo "ERR: 无 /dev/drime5_ep"; exit 1; }

echo "==== 3D LUT 寄存器 @ $EPBASE ===="
"$RD" "$EPBASE"

cat <<'EOF'

---- 偏移语义（p7 静态解出）----
+0x000 bit0     OnOff / Acc_OnOff 总开关
+0x004 bits[1:0] SelCbCr_ch  通道选择
+0x008           握手位（write-1-clear 脉冲，写=bit8 读=bit4）
                 ★ 保持为 1 = 硬件已接受启动
+0x00c           LUT0 数据物理地址  ← 换色彩就改这个
+0x010           LUT1 数据地址

---- 4 个预置缓冲 ----
0 标准 0x810fd100    1 黑白 0x81101e00（线性）
2 电影 0x81106b00    3 肤色 0x81115200（★ 出厂值）
EOF
